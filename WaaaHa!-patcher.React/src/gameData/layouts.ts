/**
 * Размещение кнопок по панелям — вручную, игроком.
 *
 * Файл правится руками, потому что универсального правила нет: в машинерии
 * производится глайдер, и хоткей глайдера настраивается у машинерии, потому что
 * игрок так прописал; машинерия строится у строителя, и её хоткей тоже задаёт он.
 * Угадать такие связи из файла биндингов нельзя.
 *
 * Формат записи для одного юнита или строения:
 *
 *   marine_hq: {
 *     // Позиция — это индекс в массиве, начиная с нуля.
 *     // Панель команд: 12 мест, четыре столба на три строки.
 *     command: ['', '', '', 'build', 'repair'],
 *
 *     // Панель команд 2: те же 12 мест.
 *     second: ['marine_armoury', 'marine_chapel'],
 *
 *     // Улучшения: 8 мест.
 *     improvements: ['military_cycle', 'builder_cycle'],
 *   },
 *
 * Пустая строка — пустое место. Оно остаётся на своей позиции: панель в игре не
 * меняет форму от выбранного юнита, и именно ради этой формы её и настраивают.
 *
 * Что здесь не описано, берётся из panels.ts по общим правилам. Описанное здесь
 * заменяет правила целиком для этого юнита — так видно, что решение принято руками,
 * а не подобралось.
 *
 * Проверить, что опечаток нет: node tools/layout.mjs check
 * Выгрузить заготовку под все юниты расы: node tools/layout.mjs export
 */
export interface UnitLayout {
  /** Основная панель команд. Не более PANEL_SLOTS мест. */
  command?: readonly (string | null)[]
  /** Вторая панель команд. Не более PANEL_SLOTS мест. */
  second?: readonly (string | null)[]
  /** Улучшения. Не более IMPROVEMENT_SLOTS мест. */
  improvements?: readonly (string | null)[]
}

